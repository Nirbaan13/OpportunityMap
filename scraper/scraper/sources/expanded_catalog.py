OT = OpportunityType


def _item(
    *,
    external_id: str,
    title: str,
    url: str,
    description: str,
    opportunity_type: OpportunityType,
    field_slugs: list[str],
    application_url: str | None = None,
    grade_min: int = 9,
    grade_max: int = 12,
    grade_eligibility: str = "High School",
    experience: str | None = None,
    eligible_countries: list[str] | None = None,
    deadline_summary: str = "Deadlines vary by year and country — check the official site",
    deadline_at: datetime | None = None,
) -> ScrapedOpportunity:
    return ScrapedOpportunity(
        external_id=external_id,
        title=title,
        source_url=url,
        application_url=application_url or url,
        description=description,
        opportunity_type=opportunity_type,
        grade_eligibility=grade_eligibility,
        grade_min=grade_min,
        grade_max=grade_max,
        eligible_countries=(
            eligible_countries
            if eligible_countries is not None
            else infer_eligible_countries(
                description,
                url,
                experience,
                title=title,
                opportunity_type=opportunity_type,
                # Expanded catalog is also mostly US/Canada/UK with international
                # markers catching global programs; unmarked leftovers default US.
                default_countries=["US"],
            )
        ),
        experience_requirements=experience,
        deadline_at=deadline_at,
        deadline_summary=deadline_summary,
        field_slugs=field_slugs,
    )


